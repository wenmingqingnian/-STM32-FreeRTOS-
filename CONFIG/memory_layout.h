/*
 * Flash 分区布局（双分区 A/B 版，STM32F103RCT6，256 KiB）
 *
 * 本文件是分区地址的【唯一权威来源】：所有模块（BOOT/BSP/CONFIG/tools）
 * 一律经本文件取地址常量，禁止任何模块硬编码分区地址。
 *
 * ===========================================================================
 * 相对旧版（CBT6 128 KiB 单 APP）的变更
 * ===========================================================================
 * 旧版（Task 16 冻结，reference：git 历史）：
 *   Boot 0x08000000 + 0x3800，APP 0x08003800 + 0x1C000（114688 B），
 *   元数据 page126/127，总量 128 KiB。
 *   实测 APP ROM 55084 B，双槽每槽仅 57344 B —— 差 212 B 放不下，
 *   故升级到 256 KiB 芯片并改为本双槽布局。
 *
 * 新版（双槽 A/B，256 KiB，高密度 F1 页 2 KiB → 128 页）：
 *   Boot  0x08000000 + 0x3800（14336 B，与旧版一致，Boot 不必重定位）
 *   ┌─ Slot A 0x08003800 + 0x1DC00（121856 B）
 *   └─ Slot B 0x08021400 + 0x1DC00（121856 B）
 *   元数据 page126/127（Flash 末尾两页）
 *
 * 容量验收（实测 APP ROM 55084 B）：
 *   每槽 121856 B，扣 2 KiB 硬余量后 119808 B，余量 64724 B —— 充裕。
 *
 * ===========================================================================
 * 为什么"两槽连续等长"（设计约束）
 * ===========================================================================
 *   - 等长：同一份 APP 源码编出的镜像两槽皆可烧，Boot 校验/擦写逻辑
 *     只需把"基址"当参数，无需按槽分叉；
 *   - 连续：Slot B 紧接 Slot A，Slot B 末尾恰为 APP_LIMIT_EXCL，无空洞，
 *     map 单一加载域检查与越界判定都最简单；
 *   - 0x200 对齐：两个槽基址相对 FLASH_BASE 都是 0x200 倍数，
 *     满足 system_stm32f10x.c 对 VTOR 偏移的对齐要求（两槽各编一份镜像）。
 *     ⚠️ 只要求 0x200，不要求 2 KiB 页倍数：SLOT_CAPACITY 是镜像越界判定
 *     上界、SLOT_B_BASE 是加载基址，二者均非擦除单元。
 *
 * ===========================================================================
 * 契约（tools/check_memory_layout.py 强制）
 * ===========================================================================
 *   - 每个常量只允许整数字面量（禁止表达式/引用其他宏）；
 *   - 派生关系（槽等长/连续/对齐/元数据双页占末尾/APP_BASE==SLOT_A_BASE 等）
 *     由 checker 交叉校验，人工改一处漏一处会直接报错退出；
 *   - LAYOUT_PROVISIONAL 必须为 0（最终布局；-—final 模式下非 0 即失败）。
 *
 */
#ifndef __MEMORY_LAYOUT_H
#define __MEMORY_LAYOUT_H

/*-----------------------------------------------------------
 * 冻结标记：0 = 最终布局（不得再改分区地址）
 *----------------------------------------------------------*/
#define LAYOUT_PROVISIONAL      0

/*-----------------------------------------------------------
 * Flash 物理边界（与 board_profile.h 的芯片事实一致）
 *   RCT6 = 256 KiB = 0x40000，高密度 F1 页 2 KiB → 共 128 页（page 0..127）
 *----------------------------------------------------------*/
#define FLASH_BASE              0x08000000UL  /* 官方起始地址 */
#define FLASH_END_EXCL          0x08040000UL  /* RCT6 = 256 KiB（boot_update.c 工厂容量寄存器门禁） */
#define FLASH_PAGE_SIZE         0x00000800UL  /* 2 KiB 页擦除粒度（高密度 F1，见 board_profile.h） */

/*-----------------------------------------------------------
 * 双页事务元数据：必须占 Flash 末尾两页（page 126/127）
 *   META_A/META_B 交替写，坏页互为回滚
 *   ⚠️ 每页 2 KiB，两条记录各占一整页——绝不可再放进同一页（同页则
 *      无法交替擦写：擦 A 会连 B 一起擦掉，"双页互为回滚"即失效）。
 *----------------------------------------------------------*/
#define META_A_BASE             0x0803F000UL  /* page 126 */
#define META_B_BASE             0x0803F800UL  /* page 127（最后一页） */

/* APP（两槽合计）可用上界（不含）：镜像不得越过元数据页 */
#define APP_LIMIT_EXCL          0x0803F000UL

/*-----------------------------------------------------------
 * Boot 分区（与旧版一致：B_final=11468 B，align_up(+2048,2048)=0x3800）
 *----------------------------------------------------------*/
#define BOOT_PART_SIZE          0x00003800UL  /* 14336 B */

/*-----------------------------------------------------------
 * 双槽 A/B（连续等长）
 *
 *   SLOT_A_BASE     = FLASH_BASE + BOOT_PART_SIZE = 0x08003800
 *   SLOT_B_BASE     = SLOT_A_BASE + SLOT_CAPACITY = 0x08021400
 *   SLOT_CAPACITY   = 0x1DC00 = 121856 B（两槽等长）
 *   APP_LIMIT_EXCL  = SLOT_B_BASE + SLOT_CAPACITY = 0x0803F000（精确，无空洞）
 *----------------------------------------------------------*/
#define SLOT_CAPACITY           0x0001DC00UL  /* 121856 B，每槽容量（两槽等长） */
#define SLOT_A_BASE             0x08003800UL  /* 活动/备用槽之一（VTOR 偏移 0x3800） */
#define SLOT_B_BASE             0x08021400UL  /* 另一槽（VTOR 偏移 0x21400） */

/*-----------------------------------------------------------
 * 槽编号（写入元数据 slot_id 字段；0 保留为"非法/擦除态"）
 *----------------------------------------------------------*/
#define SLOT_ID_A               1u
#define SLOT_ID_B               2u

/*-----------------------------------------------------------
 * 兼容别名（旧单 APP 代码路径 / 工具链仍引用 APP_BASE、APP_CAPACITY）
 *
 *   APP_BASE      = SLOT_A_BASE（默认活动槽；运行期活动槽由 Boot 决策，
 *                   本别名只用于"以 Slot A 为默认"的编译期场景，
 *                   例如工程 IROM 基址、单槽 mock 测试）
 *   APP_CAPACITY  = SLOT_CAPACITY（单槽容量；两槽等长故同值）
 *----------------------------------------------------------*/
#define APP_BASE                0x08003800UL  /* == SLOT_A_BASE */
#define APP_CAPACITY            0x0001DC00UL  /* == SLOT_CAPACITY */

/*-----------------------------------------------------------
 * VTOR 偏移（compile-time 供"两槽各编一份镜像"的工程配置使用）
 *   SLOT A 镜像：VECT_TAB_OFFSET = 0x3800
 *   SLOT B 镜像：VECT_TAB_OFFSET = 0x21400
 * 两者均为 0x200 倍数（system_stm32f10x.c 要求）。
 *----------------------------------------------------------*/
#define VECT_TAB_OFFSET_SLOT_A  0x00003800UL
#define VECT_TAB_OFFSET_SLOT_B  0x00021400UL


/*-----------------------------------------------------------
 * 修复记录（2026-10-16）
 *-----------------------------------------------------------
 * 缺陷：FLASH_PAGE_SIZE 曾为 0x400（1 KiB，中容量 F1 粒度），
 *   META_A/META_B 编为 0x0803F800 / 0x0803FC00（"page 254/255"）。
 *   但 RCT6 = RC = 高密度（本文件 BOARD_MCU_STM32F103RC 注释已自述
 *   "大容量 High Density"），官方页粒度为 2 KiB：
 *     0x0803F800 // 0x800 == 0x0803FC00 // 0x800 == page 127
 *   → 所谓"双页"实为同一物理页，"坏页互为回滚"从未成立。
 *
 * 根因：CBT6（128 KiB 中容量，1 KiB 页）换 RCT6（256 KiB 高密度，
 *   2 KiB 页）时漏改页粒度；board_profile.h 的 BOARD_FLASH_PAGE_SIZE
 *   与 check_memory_layout.py 的 FLASH_PAGE_SIZE_1K（当时名）门禁互相"确认"，
 *   使错误假设被工具链锁定。
 *
 * 修法：页粒度改 2 KiB；元数据移到 page 126/127（各占一整页）；
 *   APP 区相应缩小 2 KiB，两槽等长重算为 0x1DC00。
 *   同时放开 checker 对 SLOT_CAPACITY / SLOT_B_BASE 的页倍数要求
 *（二者非擦除单元，只需 VTOR 0x200 对齐）。
 *
 * 影响：Slot B 基址由 0x08021800 改为 0x08021400 ——
 *   **已烧录到 Slot B 的固件全部失效，需重刷**；Slot A 位置不变。
 *   Boot 分区与 Slot A 基址均未变，Boot 不必重烧。
 *-----------------------------------------------------------*/

#endif /* __MEMORY_LAYOUT_H */
