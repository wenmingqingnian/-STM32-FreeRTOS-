/*-----------------------------------------------------------
 * STOP 唤醒后 72 MHz 时钟恢复：目标侧 IO 适配
 * 
 *
 * 为 BSP/LOWPOWER/system_clock_resume.c 的纯序列实现提供寄存器适配：
 * 配置链与 SetSysClockTo72() 完全一致（Flash 2WS+预取、AHB/1 APB2/1
 * APB1/2、PLL=HSE×9、SYSCLK=PLL）。与 SystemInit() 的区别（设计 §6.6）：
 *   - 三段等待（HSERDY/PLLRDY/SWS）经后端 wait_flag 有界
 *（CLK_RESUME_TIMEOUT_LOOPS 循环上限，超时 fail-safe 返回错误码
 *     而非 SystemInit 的死循环等待）；
 *   - 不重置全局时钟状态（不写 RCC 复位序列、不动 SCB->VTOR）——
 *     SystemInit 只允许复位后调用一次。
 *
 * wait_poll 为空：STOP 唤醒后 SysTick 尚未恢复，无毫秒时基（头文件
 * 契约：超时是"循环次数上限"而非"毫秒数"）。
 * 板型无关：EXTI-only STOP（PENDING/NO_LSE）与 RTC 定时 STOP（LSE）
 * 唤醒后共用本恢复链。
 *----------------------------------------------------------*/
#include "system_clock_resume.h"

static void ClkResume_HseOn(void *self)
{
  (void)self;
  RCC->CR |= (uint32_t)RCC_CR_HSEON;
}

static u8 ClkResume_HseReady(void *self)
{
  (void)self;
  return ((RCC->CR & RCC_CR_HSERDY) != (uint32_t)RESET) ? (u8)1 : (u8)0;
}

static void ClkResume_FlashLatency72M(void *self)
{
  (void)self;
  /* 预取使能 + 2 wait states（与 SetSysClockTo72 一致；
   * HSI 8MHz 下设 72MHz 档延迟是安全方向——降频升高延迟无害）*/
  FLASH->ACR |= (uint32_t)FLASH_ACR_PRFTBE;
  FLASH->ACR &= (uint32_t)((uint32_t)~FLASH_ACR_LATENCY);
  FLASH->ACR |= (uint32_t)FLASH_ACR_LATENCY_2;
}

static void ClkResume_BusPrescalers72M(void *self)
{
  (void)self;
  /* HCLK = SYSCLK; PCLK2 = HCLK; PCLK1 = HCLK/2 */
  RCC->CFGR |= (uint32_t)RCC_CFGR_HPRE_DIV1;
  RCC->CFGR |= (uint32_t)RCC_CFGR_PPRE2_DIV1;
  RCC->CFGR |= (uint32_t)RCC_CFGR_PPRE1_DIV2;
}

static void ClkResume_PllHseX9Enable(void *self)
{
  (void)self;
  /* PLL = HSE × 9（工程为 STM32F10X_MD 非 CL：无 PLL2/PREDIV1 分支）*/
  RCC->CFGR &= (uint32_t)((uint32_t)~(RCC_CFGR_PLLSRC | RCC_CFGR_PLLXTPRE |
                                      RCC_CFGR_PLLMULL));
  RCC->CFGR |= (uint32_t)(RCC_CFGR_PLLSRC_HSE | RCC_CFGR_PLLMULL9);
  RCC->CR |= RCC_CR_PLLON;
}

static u8 ClkResume_PllReady(void *self)
{
  (void)self;
  return ((RCC->CR & RCC_CR_PLLRDY) != (uint32_t)RESET) ? (u8)1 : (u8)0;
}

static void ClkResume_SelectPllSysclk(void *self)
{
  (void)self;
  RCC->CFGR &= (uint32_t)((uint32_t)~RCC_CFGR_SW);
  RCC->CFGR |= (uint32_t)RCC_CFGR_SW_PLL;
}

static u8 ClkResume_SysclkIsPll(void *self)
{
  (void)self;
  return ((RCC->CFGR & (uint32_t)RCC_CFGR_SWS) == (uint32_t)0x08) ? (u8)1
                                                                  : (u8)0;
}

static void ClkResume_CoreClockUpdate(void *self)
{
  (void)self;
  SystemCoreClockUpdate();
}

static void ClkResume_WaitPoll(void *self)
{
  (void)self;      /* SysTick 未恢复：纯循环计数，无毫秒时基（见上）*/
}

